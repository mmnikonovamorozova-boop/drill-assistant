current_time = datetime.now().strftime("%d.%m.%Y %H:%M")

# Удобный плоский выбор разделов прямо по центру экрана
section = st.radio("Выберите раздел работы:", ["🔧 Входной контроль и ВЗД", "🚨 Осложнения при сборке", "📋 Требования инструкции"])

if section == "🔧 Входной контроль и ВЗД":
    st.subheader("Ликвидация осложнений при входном контроле")
    p_type = st.selectbox(
        "Выберите симптом / операцию:",
        ["Не выбрано", "Замер осевого люфта шпинделя ВЗД", "Резьба заклинила на первых витках", "Оценка задиров резьбы", "Обнаружена течь при гидроиспытаниях"]
    )
    
    if p_type == "Замер осевого люфта шпинделя ВЗД":
        st.info("📝 МЕТОДИКА ЗАМЕРА: Люфт = Размер А (Растянуто) - Размер Б (Сжато)")
        selected_brand = st.selectbox("Производитель ВЗД:", ["Радиус-Сервис", "ВНИИБТ", "Гидробур", "НГТ", "NOV"])
        selected_diameter = st.selectbox("Диаметр (типоразмер) двигателя:", ["98 мм", "106 мм", "120 мм", "172 мм", "240 мм"])
        
        limit_wear = 4.5
        if selected_diameter == "172 мм":
            limit_wear = 5.0
        if selected_diameter == "240 мм":
            limit_wear = 6.0
            
        size_a = st.number_input("Размер 'А' (Растянуто под своим весом), мм:", value=10.0, step=0.1)
        size_b = st.number_input("Размер 'Б' (Сжато при разгрузке на ротор), мм:", value=5.5, step=0.1)
        calculated_delta = size_a - size_b
        
        st.markdown(f"### Фактический осевой люфт: {calculated_delta:.1f} мм (Предел: {limit_wear} мм)")
        if calculated_delta > limit_wear:
            st.error("🚨 КРИТИЧЕСКИЙ ИЗНОС ОПОР! СПУСК В СКВАЖИНУ ЗАПРЕЩЕН!")
        elif calculated_delta > 0:
            st.success("✔️ ЛЮФТ В НОРМЕ. ДВИГАТЕЛЬ ДОПУЩЕН К СПУСКУ.")

    if p_type == "Резьба заклинила на первых витках":
        st.warning("Действие: СТОП вращение! Открутить назад вручную, смыть смазку.")
        ans = st.radio("Дефекты отсутствуют?", ["Не выбрано", "Да", "Нет"], key="k_r2")
        if ans == "Да":
            st.success("✔️ ДОПУСК РЕЗЬБЫ. Смазка 2/3 муфта, 1/3 ниппель. Продолжить сборку.")
        if ans == "Нет":
            st.error("🚨 ОТБРАКОВКА РЕЗЬБЫ. Вызвать резервный переводник/трубу.")

    if p_type == "Оценка задиров резьбы":
        st.warning("Действие: Оценить глубину дефектов.")
        ans = st.radio("Возможна ручная зачистка надфилем в пределах допуска?", ["Не выбрано", "Да", "Нет"], key="k_r3")
        if ans == "Да":
            st.success("✔️ ДОПУСК. Зачистить надфилем, нанести резьбовую смазку.")
        if ans == "Нет":
            st.error("🚨 ОТБРАКОВКА ЭЛЕМЕНТА. Оформить Акт дефекта.")

    if p_type == "Обнаружена течь при гидроиспытаниях":
        st.warning("Действие: СТОП насосы буровой! Сбросить избыточное давление.")
        ans = st.radio("Локализация выхода бурового раствора:", ["Не выбрано", "В замковом стыке", "Из тела корпуса ВЗД"], key="k_r4")
        if ans == "В замковом стыке":
            st.success("🔧 ТЕЧЬ В СТЫКЕ. Докрепить соединение ключами УМК до верхнего паспортного предела.")
        if ans == "Из тела корпуса ВЗД":
            st.error("🚨 ТЕЧЬ ИЗ КОРПУСА. ВЗД ЗАБРАКОВАН! Трещина корпуса или уплотнений.")

if section == "🚨 Осложнения при сборке":
    st.subheader("Карта решений при технологических осложнениях")
    p_type_2 = st.selectbox(
        "Выберите зафиксированное отклонение:",
        ["Не выбрано", "Нет пакета данных MWD / Падение давления на тесте", "Отклонение угла натяжения троса ключа УМК от 90°", "Совпадение частоты пульсаций генератора с частотой вышки"]
    )
    
    if p_type_2 == "Нет пакета данных MWD / Падение давления на тесте":
        st.error("Следствие: Срыв этапа наземной проверки КНБК на мостках.")
        st.info("Действие: Контроль сигнала. Поворот КНБК на 90 и 180 градусов относительно ротора.")
        ans = st.radio("Каротаж стабилен?", ["Не выбрано", "Да", "Нет"], key="o_r1")
        if ans == "Да":
            st.success("✔️ СПУСК РАЗРЕШЕН. Параметры ТМС в норме.")
        if ans == "Нет":
            st.error("🚨 СТОП! Подъем MWD для ревизии модулей телеметрии.")

    if p_type_2 == "Отклонение угла натяжения троса ключа УМК от 90°":
        st.error("Следствие: Скрытый недотяг / перетяг резьбы. Риск аварийного свинчивания КНБК.")
        st.info("Действие: Остановить затяжку. Замерить плечо L. Выставить угол максимально близко к 90 градусам.")
        st.warning("💡 Используйте модуль «Расчет УМК» в левом боковом меню!")
        ans = st.radio("Момент с поправкой на угол соответствует требованиям паспорта?", ["Не выбрано", "Да", "Нет"], key="o_r2")
        if ans == "Да":
            st.success("✔️ КНБК готова к спуску! Запись о проверке внесена в вахтовый журнал.")
        if ans == "Нет":
            st.error("🚨 СТОП ТЕХНОЛОГИЯ! Требуется полная перезатяжка резьбового соединения.")

    if p_type_2 == "Совпадение частоты пульсаций генератора с частотой вышки":
        st.error("Следствие: Возникновение резонанса буровой вышки: опасная вибрация конструкций.")
        st.info("Действие: Незамедлительно снизить расход буровых насосов по минимуму.")
        ans = st.radio("Раскачивание металлоконструкций вышки прекратилось?", ["Не выбрано", "Да", "Нет"], key="o_r3")
        if ans == "Да":
            st.success("✔️ Проведение теста на пониженном расходе бурового раствора.")
        if ans == "Нет":
            st.error("🚨 ЭКСТРЕННО: СТОП НАСОСЫ! Полное устранение резонанса силами буровой бригады.")

if section == "📋 Требования инструкции":
    st.subheader("Чек-лист обязательных требований инструкции")
    st.markdown("### 1. Документы моментомера УМК")
    umk_docs = st.radio("В наличии паспорт и сведения о калибровке на моментомер ключа УМК?", ["Не выбрано", "Да", "Нет"], key="ch_r1")
    if umk_docs == "Да":
        st.success("Разрешено использование ключа. Модель и дата поверки прибора внесены в эскиз КНБК.")
    if umk_docs == "Нет":
        st.error("🚨 КРИТИЧЕСКИЙ РИСК! Незамедлительно уведомить Координатора проекта. Составить Акт.")

    st.markdown("---")
    st.markdown("### 2. Работа при отрицательных температурах воздуха")
    temp_air = st.radio("Температура наружного воздуха ниже 0°C?", ["Не выбрано", "Да (Ниже нуля)", "Нет (Тепло)"], key="ch_r2")
    if temp_air == "Да (Ниже нуля)":
        st.info("❄️ ТРЕБОВАНИЕ: Обеспечить равномерный прогрев ВЗД паром. Отогреть резьбы паром.")
        st.warning("⚠️ ИСКЛЮЧИТЬ прямое направление пара во внутреннее пространство ВЗД.")
        has_steam = st.radio("Пар имеется на буровой установке?", ["Не выбрано", "Да, пар есть", "Нет пара на буровой"], key="ch_r3")
        if has_steam == "Нет пара на буровой":
            st.error("🚨 НАРУШЕНИЕ! Составить Акт об отсутствии пара. Осуществить прогрев спуском в скважину на 350-400 м.")

    st.markdown("---")
    st.markdown("### 3. Сборка гидравлического ЯСа")
    st.warning("⚠️ КАТЕГОРИЧЕСКИ ЗАПРЕЩАЕТСЯ: Зажимать полированный шток яса в клиньях ПКР!")
    st.info("💡 ПРАВИЛО: Подъем осуществлять строго с навернутыми колпачками.")
