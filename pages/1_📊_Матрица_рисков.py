# Плоское меню переключения разделов
section = st.radio(
    "Выберите технологический этап контроля КНБК:", 
    ["🔧 1. Входной контроль оборудования и ВЗД", "🚨 2. Экспертный анализ скрытых дефектов сборки", "📋 3. Технологические осложнения на устье"]
)

# =========================================================================
# РАЗДЕЛ 1: ВХОДНОЙ КОНТРОЛЬ ОБОРУДОВАНИЯ И ВЗД
# =========================================================================
if section == "🔧 1. Входной контроль оборудования и ВЗД":
    st.subheader("Модуль проведения измерений и дефектоскопии")
    p_type = st.selectbox(
        "Выберите операцию контроля:",
        ["Не выбрано", "Замер осевого люфта шпинделя ВЗД", "Инспекция предохранительного хомута (ХП)", "Обнаружена течь при гидроиспытаниях КНБК"]
    )
    
    if p_type == "Замер осевого люфта шпинделя ВЗД":
        st.info("📝 МЕТОДИКА ЗАМЕРА: Фактический люфт Δh = Размер А (Растянуто) - Размер Б (Сжато)")
        st.caption("Требование: Технолог обязан ЛИЧНО присутствовать на мостках, замер выполняется дважды!")
        selected_diameter = st.selectbox("Диаметр двигателя (ВЗД):", ["98 мм", "106 мм", "120 мм", "172 мм", "240 мм"])
        
        limit_wear = 4.5
        if selected_diameter == "172 мм":
            limit_wear = 5.0
        if selected_diameter == "240 мм":
            limit_wear = 6.0
            
        size_a = st.number_input("Размер 'А' (Вал полностью выдвинут вниз под своим весом), мм:", value=10.0, step=0.1)
        size_b = st.number_input("Размер 'Б' (Двигатель опущен на стол ротора и разгружен), мм:", value=5.5, step=0.1)
        calculated_delta = size_a - size_b
        
        st.markdown(f"### Фактический осевой люфт: {calculated_delta:.1f} мм (Паспортный предел износа: {limit_wear} мм)")
        if calculated_delta > limit_wear:
            st.error("🚨 КРИТИЧЕСКИЙ ИЗНОС ОПОР! СПУСК В СКВАЖИНУ КАТЕГОРИЧЕСКИ ЗАПРЕЩЕН! Экстренный вызов резерва.")
        elif calculated_delta > 0:
            st.success("✔️ ЛЮФТ В НОРМЕ. Инструмент допущен к спуску. Занесите Δh в эскиз КНБК.")

    if p_type == "Инспекция предохранительного хомута (ХП)":
        st.info("📋 СПРАВОЧНАЯ ТАБЛИЦА СБОРКИ ХОМУТА ПО ДИАМЕТРАМ КНБК:")
        st.code("""
        УБТ тяжелые / опорно-центрирующие элементы (240 мм) ----> 12 звеньев
        Корпус забойного двигателя / ВЗД (170-178 мм) ----------> 10 звеньев
        Переводники КНБК, ловильный инструмент (120 мм) --------> 8 звеньев
        Немагнитные УБТ малого диаметра (88-102 мм) ------------> 7 звеньев
        """, language="text")
        st.warning("⚠️ КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО: Опускание предохранительного хомута вместе с колонной труб в ствол скважины!")
        ans = st.radio("Выявлены ли скрытые дефекты, трещины, износ звеньев или отсутствие шплинтов?", ["Не выбрано", "Да, обнаружен дефект", "Нет, хомут исправен"], key="hom_r")
        if ans == "Да, обнаружен дефект":
            st.error("🚨 ХОМУТ ЗАБРАКОВАН! Использование неисправного или несмазанного хомута категорически запрещено. Составьте официальную заявку на исправный ХП и ЗИП.")
        if ans == "Нет, хомут исправен":
            st.success("✔️ КОНЕЦ ЭТАПА: Хомут готов к работе. Разрешен переход к контролю моментомера УМК.")

    if p_type == "Обнаружена течь при гидроиспытаниях КНБК":
        st.warning("Действие: СТОП насосы буровой! Сбросить избыточное давление в манифольде до 0 атм.")
        ans = st.radio("Локализация выхода бурового раствора:", ["Не выбрано", "В замковом стыке", "Из тела корпуса ВЗД"], key="tech_r")
        if ans == "В замковом стыке":
            st.success("🔧 ТЕЧЬ В СТЫКЕ. Докрепить соединение ключами УМК до верхнего паспортного предела. Используйте модуль 'Расчет УМК' в левом меню для корректировки момента!")
        if ans == "Из тела корпуса ВЗД":
            st.error("🚨 ТЕЧЬ ИЗ КОРПУСА. ВЗД ЗАБРАКОВАН! Трещина корпуса или уплотнений шпиндельной секции. Оформить рекламацию.")

# =========================================================================
# РАЗДЕЛ 2: ЭКСПЕРТНЫЙ АНАЛИЗ СКРЫТЫХ ДЕФЕКТОВ СБОРКИ
# =========================================================================
if section == "🚨 2. Экспертный анализ скрытых дефектов сборки":
    st.subheader("Предотвращение брака и аварийных ситуаций по физике процессов")
    defect_type = st.selectbox(
        "Выберите тип выявляемого дефекта соединения:",
        ["Не выбрано", "Деформация замка муфты ключами УМК ('Яйцо')", "Эффект 'Гидроклина' из-за избытка смазки", "Зажим ключами тонкостенного кожуха статора ВЗД"]
    )
    
    if defect_type == "Деформация замка муфты ключами УМК ('Яйцо')":
        st.error("⚠️ СУТЬ РИСКА: Неправильная установка челюстей УМК сминает муфту из круга в эллипс. Образуются радиальные наплывы. Верхний элемент встает с перекосом, что гарантирует промыв замка или слом КНБК при бурении!")
        st.info("📋 ИНСТРУКЦИЯ ПО ПРЕДОТВРАЩЕНИЮ: Проверять соответствие размера сухарей наружному диаметру. Использование изношенных плашек ЗАПРЕЩЕНО. Если элемент КНБК наживляется с трудом или бьет при вращении от руки — немедленно остановите сборку.")
        ans = st.radio("Обнаружены радиальные наплывы металла или эллипс муфты?", ["Не выбрано", "Да (Брак)", "Нет (Норма)"], key="def_r1")
        if ans == "Да (Брак)":
            st.critical("🚨 СВИНЧИВАНИЕ КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО! Инструмент подлежит дефектоскопии торцов и замковой части.")
        if ans == "Нет (Норма)":
            st.success("✔️ Зазор стыка замка в процессе посадки равен 0 мм. Свинчивание разрешено на первой скорости УМК/СВП.")

    if defect_type == "Эффект 'Гидроклина' из-за избытка смазки":
        st.error("⚠️ СУТЬ РИСКА: Избыточный объем смазки забивает зазоры резьбы, создавая несжимаемую гидравлическую пробку. Ключ УМК фиксирует ложный (паспортный) момент свинчивания через масло, но фактический затяг резьбы отсутствует! На забое смазка вымывается, происходит развинчивание КНБК.")
        st.info("📋 ИНСТРУКЦИЯ ПО ПРЕДОТВРАЩЕНИЮ: Тщательно удаляйте старую смазку ветошью. Нанесение новой смазки строго в пропорции: 2/3 объема в МУФТУ, 1/3 объема на НИППЕЛЬ. Категорически запрещено забивать смазку внутрь комком!")
        ans = st.radio("Резьбовая смазка нанесена по регламенту (2/3 в муфту, 1/3 на ниппель тонким слоем)?", ["Не выбрано", "Да, строго по регламенту", "Нет, смазка забита комком"], key="def_r2")
        if ans == "Нет, смазка забита комком":
            st.critical("🚨 СТОП РАБОТЫ! Развинтить соединение, полностью удалить смазку ветошью (или продуть сжатым воздухом зимой от наледи) и перенанести заново.")
        if ans == "Да, строго по регламенту":
            st.success("✔️ Риск гидроклина исключен. Фактический затяг резьбы соответствует показаниям прибора.")

    if defect_type == "Зажим ключами тонкостенного кожуха статора ВЗД":
        st.error("⚠️ СУТЬ РИСКА: Накидывание ключей УМК или клиньев ПКР на среднюю тонкостенную часть двигателя необратимо сминает стальной корпус в эллипс. Это сжимает резиновую обкладку статора, намертво заклинивая ротор ВЗД при пуске насосов, вызывая лавинообразное отслоение и деструкцию резины!")
        st.info("📋 ИНСТРУКЦИЯ ПО ПРЕДОТВРАЩЕНИЮ: Установка челюстей УМК и зажим сухарей допускается СТРОГО на утолщенные замковые пояса — верхний переводник муфты или нижний корпус шпинделя ВЗД. Перед спуском ВЗД проверять свободное вращение вала от руки ломиком!")
        ans = st.radio("Челюсти ключа УМК установлены на регулятор или крашеную среднюю часть статора?", ["Не выбрано", "Да, ошибочная установка", "Нет, установлены строго на замковые пояса"], key="def_r3")
        if ans == "Да, ошибочная установка":
            st.critical("🚨 КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО! Немедленно снимите ключи УМК. Если зажим уже был произведен — проверьте шаблонирование ротора ломиком от руки. Любое заедание — повод для отбраковки ВЗД.")
        if ans == "Нет, установлены строго на замковые пояса":
            st.success("✔️ Зона зажима выбрана верно. Корпус статора защищен от деформации.")

