import streamlit as st
from datetime import datetime

st.set_page_config(page_title="Матрица рисков", layout="wide")

st.title("🧭 Цифровой помощник инженера «Траектория-Сервис»")
st.caption("ЭКСПЕРТНАЯ СИСТЕМА ИНСПЕКЦИИ И ЛИКВИДАЦИИ ОСЛОЖНЕНИЙ ПРИ СБОРКЕ КНБК")
st.markdown("---")

well_number = st.sidebar.text_input("Номер скважины / Куст:", value="Скв. № 101, Куст 5")
engineer_name = st.sidebar.text_input("ФИО Инженера по ННБ:", value="Иванов И.И.")
field_name = st.sidebar.text_input("Месторождение:", value="Приобское")

current_time = datetime.now().strftime("%d.%m.%Y %H:%M")
report_text = ""

section = st.radio(
    "Выберите технологический этап контроля КНБК:", 
    ["1. Входной контроль оборудования и ВЗД", "2. Экспертный анализ скрытых дефектов сборки", "3. Технологические осложнения на устье"]
)

if section == "1. Входной контроль оборудования и ВЗД":
    st.subheader("Модуль проведения измерений и дефектоскопии")
    p_type = st.selectbox(
        "Выберите операцию контроля:",
        ["Не выбрано", "Замер осевого люфта шпинделя ВЗД", "Инспекция предохранительного хомута (ХП)", "Обнаружена течь при гидроиспытаниях КНБК"]
    )
    
    if p_type == "Замер осевого люфта шпинделя ВЗД":
        st.info("📝 МЕТОДИКА ЗАМЕРА: Фактический люфт = Размер А (Растянуто) - Размер Б (Сжато)")
        selected_brand = st.selectbox("Производитель оборудования ВЗД:", ["Радиус-Сервис", "ВНИИБТ", "Гидробур", "НГТ", "NOV"])
        selected_diameter = st.selectbox("Диаметр двигателя (ВЗД):", ["98 мм", "106 мм", "120 мм", "172 мм", "240 мм"])
        
        limit_wear = 4.5
        if selected_diameter == "172 мм":
            limit_wear = 5.0
        if selected_diameter == "240 мм":
            limit_wear = 6.0
            
        size_a = st.number_input("Размер 'А' (Вал полностью выдвинут вниз под своим весом), мм:", value=10.0, step=0.1)
        size_b = st.number_input("Размер 'Б' (Двигатель опущен на стол ротора и разгружен), мм:", value=5.5, step=0.1)
        calculated_delta = size_a - size_b
        
        st.markdown("### Анализ шпинделя:")
        st.write("Производитель: " + selected_brand + " | Габарит: " + selected_diameter)
        st.write("Фактический люфт: " + str(round(calculated_delta, 1)) + " мм (Предел: " + str(limit_wear) + " мм)")
        
        if calculated_delta > limit_wear:
            res_text = "🚨 КРИТИЧЕСКИЙ ИЗНОС ОПОР! СПУСК В СКВАЖИНУ КАТЕГОРИЧЕСКИ ЗАПРЕЩЕН!"
            st.error(res_text)
            report_text = "ПРОТОКОЛ ВЗД\nДата: " + current_time + "\nОбъект: " + well_number + "\nДвигатель: " + selected_brand + " " + selected_diameter + "\nИтог: " + res_text
        elif calculated_delta > 0:
            res_text = "✔️ ЛЮФТ В НОРМЕ. Двигатель допущен к спуску."
            st.success(res_text)
            report_text = "ПРОТОКОЛ ВЗД\nДата: " + current_time + "\nОбъект: " + well_number + "\nДвигатель: " + selected_brand + " " + selected_diameter + "\nИтог: " + res_text

    if p_type == "Инспекция предохранительного хомута (ХП)":
        st.info("📋 СПРАВОЧНАЯ ТАБЛИЦА ЗВЕНЬЕВ ХОМУТА: 240 мм -> 12 зв. | 172 мм -> 10 зв. | 120 мм -> 8 зв. | 88 мм -> 7 зв.")
        ans = st.radio("Выявлены ли дефекты хомута?", ["Не выбрано", "Да, обнаружен дефект", "Нет, хомут исправен"], key="hom_r")
        if ans == "Да, обнаружен дефект":
            res_text = "ХОМУТ ЗАБРАКОВАН! Требуется замена инструмента."
            st.error(res_text)
            report_text = "ПРОТОКОЛ ХОМУТА\nДата: " + current_time + "\nИтог: " + res_text
        if ans == "Нет, хомут исправен":
            res_text = "ХОМУТ ИСПРАВЕН И СМАЗАН. Допущен к работе."
            st.success(res_text)
            report_text = "ПРОТОКОЛ ХОМУТА\nДата: " + current_time + "\nИтог: " + res_text

    if p_type == "Обнаружена течь при гидроиспытаниях КНБК":
        st.warning("Действие: СТОП насосы буровой! Сбросить избыточное давление до 0 атм.")
        ans = st.radio("Локализация выхода бурового раствора:", ["Не выбрано", "В замковом стыке", "Из тела корпуса ВЗД"], key="tech_r")
        if ans == "В замковом стыке":
            res_text = "🔧 ТЕЧЬ В СТЫКЕ. Докрепить соединение ключами УМК. Используйте модуль 'Расчет УМК' в левом меню!"
            st.success(res_text)
            report_text = "ПРОТОКОЛ ГИДРОТЕСТА\nДата: " + current_time + "\nРешение: " + res_text
        if ans == "Из тела корпуса ВЗД":
            res_text = "🚨 ТЕЧЬ ИЗ КОРПУСА. ВЗД ЗАБРАКОВАН! Выявлена трещина корпуса."
            st.error(res_text)
            report_text = "ПРОТОКОЛ ГИДРОТЕСТА\nДата: " + current_time + "\nРешение: " + res_text

if section == "2. Экспертный анализ скрытых дефектов сборки":
    st.subheader("Предотвращение брака и аварийных ситуаций по физике процессов")
    defect_type = st.selectbox(
        "Выберите тип дефекта соединения:",
        ["Не выбрано", "Деформация замка муфты ключами УМК ('Яйцо')", "Эффект 'Гидроклина' из-за избытка смазки", "Зажим ключами тонкостенного кожуха статора ВЗД"]
    )
    
    if defect_type == "Деформация замка муфты ключами УМК ('Яйцо')":
        st.error("⚠️ СУТЬ РИСКА: Неправильный зажим сминает муфту в эллипс. Свинчивание приведет к промыву замка или слому КНБК!")
        ans = st.radio("Обнаружены радиальные наплывы металла или эллипс муфты?", ["Не выбрано", "Да (Брак)", "Нет (Норма)"], key="def_r1")
        if ans == "Да (Брак)":
            res_text = "СВИНЧИВАНИЕ ЗАПРЕЩЕНО! Элемент подлежит дефектоскопии."
            st.error(res_text)
            report_text = "АКТ ДЕФЕКТАЦКИИ\nДата: " + current_time + "\nВердикт: " + res_text
        if ans == "Нет (Норма)":
            res_text = "Зазор стыка замка равен 0 мм. Свинчивание разрешено."
            st.success(res_text)
            report_text = "АКТ ДЕФЕКТАЦКИИ\nДата: " + current_time + "\nВердикт: " + res_text

    if defect_type == "Эффект 'Гидроклина' из-за избытка смазки":
        st.error("⚠️ СУТЬ РИСКА: Избыток смазки создает гидравлическую пробку. Ключ фиксирует ложный момент затяжки через масло. На забое соединение раскрепится.")
        ans = st.radio("Резьбовая смазка нанесена по регламенту (2/3 в муфту, 1/3 на ниппель)?", ["Не выбрано", "Да, строго по регламенту", "Нет, смазка забита комком"], key="def_r2")
        if ans == "Нет, смазка забита комком":
            res_text = "СТОП РАБОТЫ! Требуется полностью удалить смазку ветошью и перенанести заново."
            st.error(res_text)
            report_text = "ПРОТОКОЛ СМАЗКИ\nРешение: " + res_text
        if ans == "Да, строго по регламенту":
            res_text = "Риск гидроклина исключен. Фактический затяг соответствует норме."
            st.success(res_text)
            report_text = "ПРОТОКОЛ СМАЗКИ\nРешение: " + res_text

    if defect_type == "Зажим ключами тонкостенного кожуха статора ВЗД":
        st.error("⚠️ СУТЬ РИСКА: Зажим УМК по центру статора сминает корпус, заклинивая ротор ВЗД и вызывая отслоение резины эластомера!")
        ans = st.radio("Челюсти ключа УМК установлены на регулятор или крашеную среднюю часть статора?", ["Не выбрано", "Да, ошибочная установка", "Нет, установлены строго на замковые пояса"], key="def_r3")
        if ans == "Да, ошибочная установка":
            res_text = "КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО! Снять ключи УМК. Требуется проверка вращения вала ломиком от руки."
            st.error(res_text)
            report_text = "ПРОТОКОЛ КОРПУСА ВЗД\nВердикт: " + res_text
        if ans == "Нет, установлены строго на замковые пояса":
            res_text = "Зона зажима выбрана верно (толстостенный замок)."
            st.success(res_text)
            report_text = "ПРОТОКОЛ КОРПУСА ВЗД\nВердикт: " + res_text

if section == "3. Технологические осложнения на устье":
    st.subheader("Решения при аварийных сигналах и отказах оборудования")
    p_type_2 = st.selectbox(
        "Выберите зафиксированное отклонение параметров:",
        ["Не выбрано", "Нет пакета данных MWD / Падение давления на тесте", "Отклонение угла натяжения троса ключа УМК от 90°", "Совпадение частоты пульсаций генератора с частотой вышки (Резонанс)"]
    )
    
    if p_type_2 == "Нет пакета данных MWD / Падение давления на тесте":
        st.error("Следствие: Срыв этапа наземной проверки КНБК на мостках.")
        ans = st.radio("Каротаж стабилен?", ["Не выбрано", "Да", "Нет"], key="os_r1")
        if ans == "Да":
            res_text = "СПУСК РАЗРЕШЕН. Параметры телесистемы пришли в норму."
            st.success(res_text)
            report_text = "ПРОТОКОЛ ТМС\nИтог: " + res_text
        if ans == "Нет":
            res_text = "СТОП РАБОТЫ! Требуется подъем MWD для ревизии модулей."
            st.error(res_text)
            report_text = "ПРОТОКОЛ ТМС\nИтог: " + res_text

    if p_type_2 == "Отклонение угла натяжения троса ключа УМК от 90°":
        st.error("Следствие: Риск аварийного свинчивания КНБК из-за погрешности затяжки.")
        st.info("Погрешности затяжки по регламенту: 90° (0%), 80°/100° (1.5%), 70°/110° (6.0%), 60°/120° (13.4%), 50°/130° (23.4%).")
        st.warning("💡 Ограничение: Если погрешность более 10%, запрещено дотягивать резьбу завышением давления! Переставьте лебедку. Используйте модуль 'Расчет УМК' в левом меню!")
        ans = st.radio("Момент с поправкой на угол соответствует требованиям паспорта?", ["Не выбрано", "Да", "Нет"], key="os_r2")
        if ans == "Да":
            res_text = "КНБК готова к спуску! Запись внесена в вахтовый журнал."
            st.success(res_text)
            report_text = "ПРОТОКОЛ УМК\nИтог: " + res_text
        if ans == "Нет":
            res_text = "СТОП! Требуется полная перезатяжка резьбового соединения."
            st.error(res_text)
            report_text = "ПРОТОКОЛ УМК\nИтог: " + res_text

    if p_type_2 == "Совпадение частоты пульсаций генератора с частотой вышки (Резонанс)":
        st.error("Следствие: Возникновение резонанса буровой вышки: опасная vibration конструкций.")
