import streamlit as st
from datetime import datetime

st.set_page_config(page_title="Матрица рисков", layout="wide")

st.title("🧭 Матрица рисков и ликвидации осложнений")
st.caption("ЭКСПЕРТНАЯ СИСТЕМА ЛИКВИДАЦИИ ОТКЛОНЕНИЙ ПРИ СБОРКЕ И ОПРЕССОВКЕ КНБК")
st.markdown("---")

well_number = st.sidebar.text_input("Номер скважины / Куст:", value="Скв. № 101, Куст 5")
engineer_name = st.sidebar.text_input("ФИО Инженера по ННБ:", value="Иванов И.И.")
field_name = st.sidebar.text_input("Месторождение:", value="Приобское")

current_time = datetime.now().strftime("%d.%m.%Y %H:%M")
report_text = ""

section = st.radio(
    "Выберите категорию анализа:", 
    ["1. Экспертный анализ скрытых дефектов сборки", "2. Технологические осложнения на устье"]
)

if section == "1. Экспертный анализ скрытых дефектов сборки":
    st.subheader("Предотвращение брака и аварийных ситуаций по физике процессов")
    defect_type = st.selectbox(
        "Выберите тип дефекта соединения:",
        ["Не выбрано", "Деформация замка муфты ключами УМК ('Яйцо')", "Эффект 'Гидроклина' из-за избытка смазки", "Зажим ключами тонкостенного кожуха статора ВЗД"]
    )
    
    if defect_type == "Деформация замка муфты ключами УМК ('Яйцо')":
        st.error("⚠️ СУТЬ РИСКА: Неправильный зажим сминает муфту в эллипс. Свинчивание приведет к промыву замка или слому КНБК!")
        ans = st.radio("Обнаружены радиальные наплывы металла или эллипс муфты?", ["Не выбрано", "Да (Брак)", "Нет (Норма)"], key="def_r1")
        if ans == "Да (Брак)":
            res_text = "СВИНЧИВАНИЕ ЗАПРЕЩЕНО! Элемент подлежит дефектоскопии."
            st.error(res_text)
            report_text = "АКТ ДЕФЕКТАЦКИИ\nДата: " + current_time + "\nВердикт: " + res_text
        if ans == "Нет (Норма)":
            res_text = "Зазор стыка замка равен 0 мм. Свинчивание разрешено."
            st.success(res_text)
            report_text = "АКТ ДЕФЕКТАЦКИИ\nДата: " + current_time + "\nВердикт: " + res_text

    if defect_type == "Эффект 'Гидроклина' из-за избытка смазки":
        st.error("⚠️ СУТЬ РИСКА: Избыток смазки создает гидравлическую пробку. Ключ фиксирует ложный момент затяжки через масло. На забое соединение раскрепится.")
        ans = st.radio("Резьбовая смазка нанесена по регламенту (2/3 в муфту, 1/3 на ниппель)?", ["Не выбрано", "Да, строго по регламенту", "Нет, смазка забита комком"], key="def_r2")
        if ans == "Нет, смазка забита комком":
            res_text = "СТОП РАБОТЫ! Требуется полностью удалить смазку ветошью и перенанести заново."
            st.error(res_text)
            report_text = "ПРОТОКОЛ СМАЗКИ\nРешение: " + res_text
        if ans == "Да, строго по регламенту":
            res_text = "Риск гидроклина исключен. Фактический затяг соответствует норме."
            st.success(res_text)
            report_text = "ПРОТОКОЛ СМАЗКИ\nРешение: " + res_text

    if defect_type == "Зажим ключами тонкостенного кожуха статора ВЗД":
        st.error("⚠️ СУТЬ РИСКА: Зажим УМК по центру статора сминает корпус, заклинивая ротор ВЗД и вызывая отслоение резины эластомера!")
        ans = st.radio("Челюсти ключа УМК установлены на регулятор или крашеную среднюю часть статора?", ["Не выбрано", "Да, ошибочная установка", "Нет, установлены строго на замковые пояса"], key="def_r3")
        if ans == "Да, ошибочная установка":
            res_text = "КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО! Снять ключи УМК. Требуется проверка вращения вала ломиком от руки."
            st.error(res_text)
            report_text = "ПРОТОКОЛ КОРПУСА ВЗД\nВердикт: " + res_text
        if ans == "Нет, установлены строго на замковые пояса":
            res_text = "Зона зажима выбрана верно (толстостенный замок)."
            st.success(res_text)
            report_text = "ПРОТОКОЛ КОРПУСА ВЗД\nВердикт: " + res_text

if section == "2. Технологические осложнения на устье":
    st.subheader("Решения при аварийных сигналах и отказах оборудования")
    p_type_2 = st.selectbox(
        "Выберите зафиксированное отклонение параметров:",
        [
            "Не выбрано", 
            "1. РЕЗЬБА ЗАКЛИНИЛА / ЗАДИРЫ СТЫКА", 
            "2. ОБНАРУЖЕНА ТЕЧЬ ПРИ ОПРЕССОВКЕ", 
            "3. НЕТ ПАКЕТА ДАННЫХ MWD / ПАДЕНИЕ ДАВЛЕНИЯ НА ТЕСТЕ", 
            "4. ОТКЛОНЕНИЕ УГЛА НАТЯЖЕНИЯ ТРОСА КЛЮЧА УМК ОТ 90°", 
            "5. СОВПАДЕНИЕ ЧАСТОТЫ ПУЛЬСАЦИЙ ГЕНЕРАТОРА С ЧАСТОТОЙ ВЫШКИ (РЕЗОНАНС)"
        ]
    )

    if p_type_2 == "1. РЕЗЬБА ЗАКЛИНИЛА / ЗАДИРЫ СТЫКА":
        st.warning("Первичное действие: СТОП вращение! Открутить элемент назад вручную, полностью смыть смазку.")
        ans_z = st.radio("Глубина дефектов и заусенцев на замке допускает ручную зачистку надфилем?", ["Не выбрано", "Да (Допуск резьбы)", "Нет (Брак)"], key="z_r_3")
        if ans_z == "Да (Допуск резьбы)":
            res_text = "✔️ ДОПУСК РЕЗЬБЫ. Зачистить надфилем. Смазка 2/3 в муфту. Продолжить сборку КНБК."
            st.success(res_text)
            report_text = "ПРОТОКОЛ КНБК (РЕЗЬБА)\nИтог: " + res_text
        if ans_z == "Нет (Брак)":
            res_text = "🚨 ОТБРАКОВКА РЕЗЬБЫ. ОТБРАКОВКА трубы/переводника. Оформить Акт дефекта, вызвать резерв."
            st.error(res_text)
            report_text = "ПРОТОКОЛ КНБК (РЕЗЬБА)\nИтог: " + res_text

    if p_type_2 == "2. ОБНАРУЖЕНА ТЕЧЬ ПРИ ОПРЕССОВКЕ":
        st.warning("Действие: СТОП насосы буровой! Сбросить избыточное давление в манифольде до 0 атм.")
        ans = st.radio("Локализация выхода бурового раствора при гидроиспытаниях КНБК?", ["Не выбрано", "В замковом стыке (В замке)", "Из тела корпуса ВЗД (Из тела)"], key="tech_r")
        if ans == "В замковом стыке (В замке)":
            res_text = "🔧 ТЕЧЬ В СТЫКЕ. Докрепить соединение ключами УМК до верхнего паспортного предела. Используйте модуль 'Расчет УМК' в левом меню!"
            st.success(res_text)
            report_text = "ПРОТОКОЛ ОПРЕССОВКИ\nРешение: " + res_text
        if ans == "Из тела корпуса ВЗД (Из тела)":
            res_text = "🚨 ТЕЧЬ ИЗ КОРПУСА. ВЗД ЗАБРАКОВАН! Трещина корпуса или уплотнений. Оформить рекламацию."
            st.error(res_text)
            report_text = "ПРОТОКОЛ ОПРЕССОВКИ\nРешение: " + res_text
            
    if p_type_2 == "3. НЕТ ПАКЕТА ДАННЫХ MWD / ПАДЕНИЕ ДАВЛЕНИЯ НА ТЕСТЕ":
        st.error("Следствие: Срыв этапа наземной проверки КНБК на мостках.")
        st.info("Действие: Контроль сигнала. Поворот КНБК на 90° и 180° относительно ротора.")
        ans = st.radio("Каротаж стабилен?", ["Не выбрано", "Да", "Нет"], key="os_r1")
        if ans == "Да":
            res_text = "СПУСК РАЗРЕШЕН. Параметры телесистемы пришли в норму."
            st.success(res_text)
            report_text = "ПРОТОКОЛ ТМС\nИтог: " + res_text
        if ans == "Нет":
            res_text = "СТОП РАБОТЫ! Требуется подъем MWD для ревизии модулей телеметрии."
            st.error(res_text)
            report_text = "ПРОТОКОЛ ТМС\nИтог: " + res_text

    if p_type_2 == "4. ОТКЛОНЕНИЕ УГЛА НАТЯЖЕНИЯ ТРОСА КЛЮЧА УМК ОТ 90°":
        st.error("Следствие: Риск аварийного свинчивания КНБК из-за погрешности затяжки.")
        st.info("Погрешности затяжки по регламенту: 90° (0%), 80°/100° (1.5%), 70°/110° (6.0%), 60°/120° (13.4%), 50°/130° (23.4%).")
        st.warning("💡 Ограничение: Если погрешность более 10%, запрещено дотягивать резьбу завышением давления! Переставьте лебедку. Используйте модуль 'Расчет УМК' в левом меню!")
        ans = st.radio("Момент с поправкой на угол соответствует требованиям паспорта?", ["Не выбрано", "Да", "Нет"], key="os_r2")
        if ans == "Да":
            res_text = "КНБК готова к спуску! Запись внесена в вахтовый журнал."
            st.success(res_text)
            report_text = "ПРОТОКОЛ УМК\nИтог: " + res_text
        if ans == "Нет":
            res_text = "СТОП! Требуется полная перезатяжка резьбового соединения."
            st.error(res_text)
            report_text = "ПРОТОКОЛ УМК\nИтог: " + res_text

    if p_type_2 == "5. СОВПАДЕНИЕ ЧАСТОТЫ ПУЛЬСАЦИЙ ГЕНЕРАТОРА С ЧАСТОТОЙ ВЫШКИ (РЕЗОНАНС)":
        st.error("Следствие: Возникновение резонанса буровой вышки: опасная вибрация конструкций.")
        ans = st.radio("В ходе поверки зафиксировано сильное раскачивание металлоконструкций вышки?", ["Не выбрано", "Да, вышка раскачивается", "Нет, в норме"], key="os_r3")
        if ans == "Да, вышка раскачивается":
            res_text = "НЕЗАМЕДЛИТЕЛЬНО СНИЗИТЬ РАСХОД НАСОСОВ ДО МИНИМУМА! При сильном раскачивании — СТОП НАСОСЫ."
            st.error(res_text)
            report_text = "ПРОТОКОЛ РЕЗОНАНСА\nВердикт: " + res_text
        if ans == "Нет, в норме":
            res_text = "Тест успешен. Амплитуда колебаний в норме (3–10 мм). Оборудование готово."
            st.success(res_text)
            report_text = "ПРОТОКОЛ РЕЗОНАНСА\nВердикт: " + res_text

if report_text != "":
    st.markdown("---")
    st.subheader("📥 Экспорт результатов проверки")
    with st.expander("👀 Посмотреть предпросмотр протокола"):
        st.code(report_text, language="text")
    st.download_button(
        label="💾 Скачать официальный отчет (.TXT)",
        data=report_text,
        file_name="Протокол_КНБК.txt",
        mime="text/plain"
    )
